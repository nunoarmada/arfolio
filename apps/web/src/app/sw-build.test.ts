import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const swPath = fileURLToPath(new URL('../../public/sw.js', import.meta.url));

/** The precache manifest @serwist/next injects: `{'revision':'abc'|null,'url':'/x'}` entries. */
function precacheEntries(source: string): { url: string; revision: string | null }[] {
  return [...source.matchAll(/\{'revision':(null|'[^']*'),'url':'([^']*)'\}/g)].map((m) => ({
    url: m[2]!,
    revision: m[1] === 'null' ? null : m[1]!.slice(1, -1),
  }));
}

// public/sw.js is generated by `next build` (@serwist/next). It is absent in a plain `pnpm test`
// (CI runs the tests before the build), so this check only runs where a build already happened:
// locally after `pnpm --filter @arfolio/web build`.
describe.skipIf(!existsSync(swPath))('built service worker (public/sw.js)', () => {
  const entries = precacheEntries(existsSync(swPath) ? readFileSync(swPath, 'utf8') : '');

  it('precaches /offline with a build revision', () => {
    const offline = entries.filter((e) => e.url === '/offline');
    expect(offline).toHaveLength(1);
    expect(offline[0]!.revision).toBeTruthy();
  });

  it('precaches hashed build assets', () => {
    expect(entries.some((e) => e.url.startsWith('/_next/static/chunks/'))).toBe(true);
  });

  it('precaches no page, RSC payload or API response besides /offline', () => {
    const others = entries.filter(
      (e) => e.url !== '/offline' && !e.url.startsWith('/_next/static/'),
    );
    expect(others).toEqual([]);
  });
});
