import { getTranslations } from 'next-intl/server';
import { headers } from 'next/headers';
import type { Metadata } from 'next';
import { InsightsNav } from '@/components/insights/insights-nav';
import { PageHeader } from '@/components/page-header';
import { ReportAutoRefresh } from '@/components/reports/pending-poll';
import { ReportStatusRegion } from '@/components/reports/status-region';
import { ReportList } from '@/components/reports/report-list';
import { AiStateCard, GenerateCard } from '@/components/reports/state-cards';
import { formatMonth } from '@/lib/dates';
import { loadReportList, loadReportsContext } from '@/server/reports-data';
import { toServiceCtx } from '@/server/service-ctx';
import { requireMember } from '@/server/session';
import { PageContainer } from '@/components/page-container';

export async function generateMetadata(): Promise<Metadata> {
  return { title: (await getTranslations('insights'))('title') };
}

const MONTH = /^\d{4}-(0[1-9]|1[0-2])$/;

const first = (value: string | string[] | undefined): string | undefined =>
  Array.isArray(value) ? value[0] : value;

/**
 * Análises › Relatórios: one row per month, newest first, each with its state, headline and
 * anomaly count. The last three closed months are always listed, report or not, so the tab is
 * useful without AI. A month's report is generated by the worker; owners and members can ask for
 * the last closed month here. Viewers read only.
 */
export default async function ReportsPage({
  searchParams,
}: {
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}) {
  const [session, raw, t, insights] = await Promise.all([
    requireMember(await headers()),
    searchParams,
    getTranslations('reports'),
    getTranslations('insights'),
  ]);
  const ctx = toServiceCtx(session);
  const rc = await loadReportsContext(ctx);
  const beforeParam = first(raw.before);
  const before = beforeParam && MONTH.test(beforeParam) ? beforeParam : null;
  const data = await loadReportList(ctx, rc, before);

  const latest = data.rows.find((r) => r.month === rc.lastClosed);
  const missingLatest = before === null && (!latest || latest.status === 'none');
  const blocked = !rc.aiAvailable || !rc.aiEnabled;
  const latestLabel = formatMonth(`${rc.lastClosed}-01`, rc.locale);

  return (
    <PageContainer className="grid grid-cols-1 gap-6 [&>header]:mb-0">
      <PageHeader title={insights('title')} tabs={<InsightsNav current="reports" />} />
      <ReportStatusRegion
        status={latest?.status ?? 'none'}
        messages={{
          pending: t('live.requested', { month: latestLabel }),
          ready: t('live.ready', { month: latestLabel }),
          failed: t('live.failed', { month: latestLabel }),
        }}
      />
      <section aria-labelledby="reports-title" className="grid grid-cols-1 gap-4">
        <div className="grid grid-cols-1 gap-1">
          <h2 id="reports-title" className="text-lg font-semibold">
            {t('list.title')}
          </h2>
          <p className="text-sm text-muted-foreground">{t('list.intro')}</p>
        </div>
        {blocked ? (
          <AiStateCard rc={rc} />
        ) : missingLatest ? (
          <GenerateCard month={rc.lastClosed} monthLabel={latestLabel} rc={rc} />
        ) : null}
        <ReportList data={data} ctx={ctx} rc={rc} />
        {data.anyPending ? <ReportAutoRefresh /> : null}
      </section>
    </PageContainer>
  );
}
