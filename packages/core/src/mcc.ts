/** Human label of a merchant category code, or undefined when unknown or malformed. */
export function mccLabel(code: string | null | undefined, locale: MccLocale): string | undefined {
  if (!isValidMcc(code)) return undefined;
  const entry =
    MCC_LABELS[code] ??
    MCC_RANGES.find(([from, to]) => Number(code) >= from && Number(code) <= to)?.[2];
  return entry?.[locale];
}
