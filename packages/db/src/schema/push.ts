import { index, integer, pgTable, text, timestamp, unique, uuid } from 'drizzle-orm/pg-core';
import { organization, user } from './auth.js';

// RLS (policy), the claim_push_endpoint() function and its grant live in the custom SQL migration,
// not here.

/**
 * One Web Push subscription: a browser/device of one user in one household. The endpoint is unique
 * across ALL households (a device belongs to whoever subscribed last; see claim_push_endpoint in
 * the RLS migration for how a subscription moves between households).
 */
export const pushSubscription = pgTable(
  'push_subscription',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    householdId: text('household_id')
      .notNull()
      .references(() => organization.id, { onDelete: 'cascade' }),
    /** Cascades with the account; a membership ending is handled by the member DELETE trigger (0028). */
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    endpoint: text('endpoint').notNull(),
    /** Client public key (base64url, 65 bytes) used to encrypt the payload end to end. */
    p256dh: text('p256dh').notNull(),
    /** Client auth secret (base64url, 16 bytes). */
    auth: text('auth').notNull(),
    userAgent: text('user_agent'),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    lastSuccessAt: timestamp('last_success_at', { withTimezone: true }),
    failureCount: integer('failure_count').notNull().default(0),
    /** Backoff: no delivery attempt before this instant. Null means "any time". */
    nextAttemptAt: timestamp('next_attempt_at', { withTimezone: true }),
  },
  (t) => [
    unique('push_subscription_endpoint_unique').on(t.endpoint),
    index('push_subscription_household_user_idx').on(t.householdId, t.userId),
  ],
);

/**
 * Installation-wide secrets: the VAPID key pair generated by the app itself (row `vapid`) and the
 * owner-editable integration settings (rows `setting:<key>`). Deliberate exception to the
 * household-scoped convention: a global table with no RLS, reached by the unprivileged role
 * through the blanket grants from ensureAppRole, like `sign_in_failure`. Secret values are stored
 * encrypted with ENCRYPTION_KEY (AES-GCM, AAD `instance:<name>`), which the app already holds.
 */
export const instanceSecret = pgTable('instance_secret', {
  name: text('name').primaryKey(),
  value: text('value').notNull(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  /** User id of whoever last wrote the row; null for rows the app generated itself (`vapid`). */
  updatedBy: text('updated_by'),
});
